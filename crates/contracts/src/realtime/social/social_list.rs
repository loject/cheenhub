//! Контракты страницы объединённого списка друзей и личных собеседников.
//!
//! Realtime-запрос возвращает единую выборку принятых друзей и участников
//! существующих личных диалогов. Отдельный поиск новых пользователей
//! остаётся самостоятельной операцией.

use serde::{Deserialize, Serialize};

use crate::presence::UserPresence;
use crate::rest::{DmConversationSummary, DmLastMessageSummary, UserRelationStatus};

/// Запрашивает страницу списка друзей и личных собеседников текущего пользователя.
///
/// Поиск выполняется по никнейму без учёта регистра до пагинации.
/// Пустой запрос возвращает всех участников. Курсор привязан к нормализованному
/// поисковому запросу и не применяется после его изменения. Сервер использует
/// 50 записей по умолчанию и допускает лимит от 1 до 100; значения вне диапазона
/// отклоняются. Курсор не предназначен для разбора клиентом.
#[derive(Debug, Clone, PartialEq, Eq, Default, Serialize, Deserialize)]
pub struct ListSocialEntries {
    /// Необязательная подстрока никнейма; пробелы по краям игнорируются сервером.
    pub query: Option<String>,
    /// Непрозрачный курсор следующей страницы в рамках того же поиска.
    pub cursor: Option<String>,
    /// Необязательный максимальный размер страницы от 1 до 100.
    pub limit: Option<u32>,
}

/// Один участник объединённого списка — друг или собеседник из существующего ЛС.
///
/// Сервер выдаёт не более одной записи на пользователя. Друзья без диалога
/// включаются с `conversation: None`; пользователь вне друзей попадает в список
/// только при наличии личного диалога. Список сортируется по времени последнего
/// неудалённого сообщения (новые первыми), затем по нормализованному никнейму
/// и идентификатору пользователя. Нормализация никнейма должна быть одинаковой
/// для фильтрации, сортировки и формирования курсора. Участники без сообщений
/// идут после остальных.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct SocialListEntrySummary {
    /// Стабильный идентификатор второго пользователя в формате UUID.
    pub user_id: String,
    /// Актуальный публичный никнейм пользователя.
    pub nickname: String,
    /// Публичный URL аватара, если он настроен.
    pub avatar_url: Option<String>,
    /// Отношение к пользователю; только `Friends` означает принятую дружбу.
    pub relation: Option<UserRelationStatus>,
    /// Присутствие друга; для пользователя вне друзей равно `None`.
    pub presence: Option<UserPresence>,
    /// Существующий личный диалог или `None`, если друг ещё не открывал ЛС.
    ///
    /// При наличии диалога его `relation` совпадает с отношением этой записи;
    /// счётчик непрочитанных берётся из `conversation.unread_count`.
    pub conversation: Option<DmConversationSummary>,
    /// Последнее неудалённое сообщение для предпросмотра и сортировки.
    pub last_message: Option<DmLastMessageSummary>,
}

/// Возвращает страницу общего списка с курсором продолжения.
///
/// Дубликаты пользователей исключаются до применения размера страницы и курсора.
/// `has_more` истинно ровно тогда, когда присутствует `next_cursor`.
/// Страницы отражают актуальное состояние, а не неизменяемый снимок: при новых
/// сообщениях или переименовании пользователя между запросами границы могут
/// сместиться. После обновления списка клиент начинает пагинацию заново.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct SocialEntries {
    /// Пользователи текущей страницы в серверном порядке.
    pub entries: Vec<SocialListEntrySummary>,
    /// Непрозрачный курсор следующей страницы, если она существует.
    pub next_cursor: Option<String>,
    /// Признак наличия записей после текущей страницы.
    pub has_more: bool,
}
