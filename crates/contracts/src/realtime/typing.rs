//! Общие контракты индикатора набора текста.

use serde::{Deserialize, Serialize};

/// Снимок участника, который сейчас печатает сообщение.
///
/// Используется и в снимке состояния комнаты или диалога, и в событии о начале
/// или завершении набора. Идентификатор остается строкой, потому что контракт
/// отдается по проводу, а внутри бэкенда работает с `Uuid`.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct TypingAuthor {
    /// Идентификатор пользователя, который печатает сообщение.
    pub user_id: String,
    /// Никнейм автора на момент формирования события.
    pub nickname: String,
    /// Публичный URL аватара автора, если он настроен.
    pub avatar_url: Option<String>,
}
