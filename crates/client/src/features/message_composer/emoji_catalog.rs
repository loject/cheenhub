//! Локальный каталог Unicode-эмодзи и русских поисковых названий.

#[derive(Clone, Copy, PartialEq)]
pub(super) struct Emoji {
    pub(super) symbol: &'static str,
    pub(super) name: &'static str,
    pub(super) category: usize,
}

pub(super) const CATEGORIES: &[&str] =
    &["Смайлы", "Жесты", "Природа", "Еда", "Предметы", "Символы"];

pub(super) fn filtered_emojis(query: &str, category: Option<usize>) -> Vec<Emoji> {
    let query = query.trim().to_lowercase();
    EMOJIS
        .iter()
        .map(|&(symbol, name, category)| Emoji {
            symbol,
            name,
            category,
        })
        .filter(|emoji| {
            category.is_none_or(|category| emoji.category == category)
                && (query.is_empty() || emoji.name.contains(&query) || emoji.symbol == query)
        })
        .collect()
}

